-- 1. Patient encounters with readmission risk
CREATE TABLE encounters (
    encounter_id              BIGINT        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    patient_nbr               BIGINT        NOT NULL,
    age                       VARCHAR(10),              -- e.g. '[70-80)'
    time_in_hospital          INT           CHECK (time_in_hospital >= 0),
    number_inpatient          INT           DEFAULT 0,
    number_emergency          INT           DEFAULT 0,
    number_outpatient         INT           DEFAULT 0,
    num_medications           INT           DEFAULT 0,
    num_lab_procedures        INT           DEFAULT 0,
    discharge_disposition_id  INT,
    admission_type_id         INT,
    readmitted                VARCHAR(5),               -- 'NO', '<30', '>30'
    risk_score                NUMERIC(5,4),             -- e.g. 0.8731
    risk_level                VARCHAR(10)
                              CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH'))
);

CREATE INDEX idx_encounters_patient    ON encounters (patient_nbr);
CREATE INDEX idx_encounters_risk_level ON encounters (risk_level);

-- 2. Interventions linked to encounters
CREATE TABLE interventions (
    intervention_id  SERIAL        PRIMARY KEY,
    encounter_id     BIGINT        NOT NULL
                     REFERENCES encounters (encounter_id) ON DELETE CASCADE,
    status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING'
                     CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    assigned_to      VARCHAR(100),
    notes            TEXT,
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_interventions_encounter ON interventions (encounter_id);
CREATE INDEX idx_interventions_status    ON interventions (status);

